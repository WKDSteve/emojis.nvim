---@module 'emojis.catalog'
--- The built-in emoji catalog: glyph, shortcode label and search terms.
---
--- Pure data plus one flattening pass, no Neovim API. `config/DEFAULTS.lua`
--- derives both the insert picker's `picks` and the replace/unreplace `names`
--- map from `M.entries()`, so one row feeds both features.
---
--- Rows are grouped into sections. A section carries its own search terms
--- (`en`, `de`) that every row in it inherits, so "pfeil" finds every arrow
--- and "ampel" every traffic-light colour without repeating the word on each
--- row. A row is `{ glyph, label, en?, de? }`:
---   - `label` is the shortcode without colons (GitHub/gemoji names where one
---     exists). It must match `[%w_+]+`, the token `unreplace` parses, and be
---     unique.
---   - the glyph's first codepoint is the `names` key, so it must be unique
---     too (TESTS/catalog_spec.lua checks both). That is why keycaps and flags
---     are absent: their first codepoint is a digit or a lone regional letter.
---   - `en`/`de` are extra space-separated search words. German words with
---     umlauts or ß are also indexed in their ASCII spelling ("gruen",
---     "weiss"), so a prompt typed without umlauts finds them too.
---
--- The order is the picker's starting order (before usage reorders it):
--- the developer-shaped sections come first.

